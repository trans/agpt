#!/usr/bin/env python3
"""Build static experiment pages from rnd/*/README.md front matter.

Requires PyYAML (also used by rnd_front_matter.py) and markdown-it-py.
Run from anywhere: python3 src/tools/build_experiment_pages.py
"""

from __future__ import annotations

import datetime as dt
import html
import json
import posixpath
import re
import subprocess
import sys
import unicodedata
from functools import lru_cache
from pathlib import Path
from urllib.parse import quote, urlsplit

from markdown_it import MarkdownIt
from markdown_it.token import Token
from rnd_front_matter import split_front_matter, validate_entry

ROOT = Path(__file__).resolve().parents[2]
RND = ROOT / "rnd"
OUTPUT = ROOT / "site" / "experiments"
REPO = "https://github.com/trans/agpt"
RAW = "https://raw.githubusercontent.com/trans/agpt/main"
GENERATED_MARKER = "<!-- Generated by src/tools/build_experiment_pages.py; edit rnd/*/README.md instead. -->"
FIXES = (
    ("pre-loss-fix", dt.date(2026, 5, 26), "the 2026-05-26 loss-normalization fix"),
    ("pre-race-fix", dt.date(2026, 9, 24), "the 2026-09-24 CUDA kernel race fix"),
    ("truncated-ancestor-gradient", dt.date(2026, 9, 28), "the 2026-09-28 exact ancestor backward"),
)
MD = MarkdownIt("default", {"html": False})


def escape(value: object) -> str:
    return html.escape(str(value), quote=True)


def date_value(value: object) -> dt.date | None:
    if isinstance(value, dt.datetime):
        return value.date()
    if isinstance(value, dt.date):
        return value
    if value:
        try:
            return dt.date.fromisoformat(str(value)[:10])
        except ValueError:
            pass
    return None


def published_readmes() -> list[Path]:
    """Include tracked and new nonignored records; omit local scratch directories."""
    command = [
        "git", "ls-files", "--cached", "--others", "--exclude-standard", "-z",
        "--", "rnd/*/README.md",
    ]
    result = subprocess.run(command, cwd=ROOT, check=True, capture_output=True)
    paths = [ROOT / part.decode() for part in result.stdout.split(b"\0") if part]
    return sorted(path for path in paths if path.is_file())


def orchestrator_runs(directory: Path) -> dict[str, dt.date]:
    dates = {}
    for child in directory.iterdir():
        if not child.is_dir():
            continue
        meta_path, result_path = child / "meta.json", child / "result.json"
        if not (meta_path.is_file() and result_path.is_file()):
            continue
        try:
            result = json.loads(result_path.read_text(encoding="utf-8"))
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError):
            continue
        if not isinstance(result, dict) or "metrics" not in result:
            continue
        run_date = date_value(result.get("started_utc")) or date_value(meta.get("started_utc"))
        if run_date:
            dates[child.name] = run_date
    return dates


@lru_cache(maxsize=None)
def tag_paths(tag: str) -> tuple[str, ...]:
    result = subprocess.run(
        ["git", "ls-tree", "-r", "--name-only", tag, "--", "rnd"],
        cwd=ROOT, check=True, capture_output=True, text=True,
    )
    return tuple(result.stdout.splitlines())


def run_reference(slug: str, fm: dict, run: str) -> tuple[str, dt.date | None]:
    """Resolve a headline run on main or its archived tag."""
    if run.startswith("rnd/"):
        relative = run.rstrip("/")
    else:
        relative = f"rnd/{slug}/{run}"
    on_main = ROOT / relative
    tag = fm["code"].get("tag") if isinstance(fm["code"], dict) else None
    if not on_main.is_dir() and tag:
        suffix = f"/{run}/result.json"
        candidates = [path for path in tag_paths(tag) if path.endswith(suffix)]
        if candidates:
            relative = candidates[0][:-len("/result.json")]
    reference = "main" if (ROOT / relative).is_dir() else tag
    if reference:
        url = REPO + "/tree/" + quote(str(reference), safe="/-._~") + "/" + quote(relative, safe="/-._~")
    else:
        url = repo_url(relative, is_dir=True)

    result_path = ROOT / relative / "result.json"
    meta_path = ROOT / relative / "meta.json"
    if reference == "main" and result_path.is_file() and meta_path.is_file():
        try:
            result = json.loads(result_path.read_text(encoding="utf-8"))
            meta = json.loads(meta_path.read_text(encoding="utf-8"))
            if "metrics" in result:
                return url, date_value(result.get("started_utc")) or date_value(meta.get("started_utc"))
        except (OSError, json.JSONDecodeError):
            pass
    elif reference and reference != "main":
        try:
            result = json.loads(subprocess.run(
                ["git", "show", f"{reference}:{relative}/result.json"],
                cwd=ROOT, check=True, capture_output=True, text=True,
            ).stdout)
            meta = json.loads(subprocess.run(
                ["git", "show", f"{reference}:{relative}/meta.json"],
                cwd=ROOT, check=True, capture_output=True, text=True,
            ).stdout)
            if "metrics" in result:
                return url, date_value(result.get("started_utc")) or date_value(meta.get("started_utc"))
        except (subprocess.CalledProcessError, json.JSONDecodeError):
            pass
    return url, None


def records() -> list[dict]:
    result = []
    errors = []
    for path in published_readmes():
        fm, body = split_front_matter(path.read_text(encoding="utf-8"))
        entry_errors, _ = validate_entry(str(path.parent), fm, check_numbers=False)
        if entry_errors:
            errors.extend(f"{path.relative_to(ROOT)}: {error}" for error in entry_errors)
            continue
        slug = path.parent.name
        runs = orchestrator_runs(path.parent)
        headline_runs = {}
        for item in fm.get("headline") or []:
            if item.get("run"):
                url, date = run_reference(slug, fm, str(item["run"]))
                headline_runs[str(item["run"])] = (url, date)
        result.append({
            "slug": slug,
            "fm": fm,
            "body": body,
            "runs": runs,
            "headline_runs": headline_runs,
        })
    if errors:
        raise ValueError("Front matter validation failed:\n" + "\n".join(errors))
    return result


def headline_caveats(fm: dict, date: dt.date | None) -> list[tuple[str, str]]:
    date = date or date_value(fm.get("updated"))
    output = []
    for name, cutoff, fix in FIXES:
        if name == "truncated-ancestor-gradient" and fm["family"] != "attention":
            continue
        if date and date < cutoff:
            output.append((name, "This result predates " + fix + "."))
    if fm["eval"] == "legacy":
        output.append(("legacy-eval", "Uses a historical evaluation protocol; compare only within that protocol."))
    return output


def run_history_summary(record: dict) -> str:
    dates = list(record["runs"].values())
    if not dates:
        return ""
    details = []
    for name, cutoff, fix in FIXES:
        if name == "truncated-ancestor-gradient" and record["fm"]["family"] != "attention":
            continue
        affected = sum(date < cutoff for date in dates)
        if affected:
            details.append(f"{affected} of {len(dates)} predate {fix}")
    if not details:
        return ""
    return '<p class="run-history"><strong>Run history:</strong> ' + escape("; ".join(details)) + ".</p>"


def badge(label: str, css_class: str = "", title: str = "") -> str:
    cls = ("badge " + css_class).strip()
    tooltip = f' title="{escape(title)}"' if title else ""
    return f'<span class="{escape(cls)}"{tooltip}>{escape(label)}</span>'


def badge_row(fm: dict) -> str:
    items = [
        badge(fm["kind"], "badge-kind"),
        badge(fm["status"], "badge-status"),
        badge(fm["outcome"], "badge-outcome outcome-" + fm["outcome"].replace("/", "-")),
        badge(fm["family"], "badge-family"),
        badge("eval: " + fm["eval"], "badge-eval"),
    ]
    return '<div class="badge-row">' + "".join(items) + "</div>"


def repo_url(path: str, is_dir: bool = False, raw: bool = False) -> str:
    encoded = quote(path, safe="/-._~")
    if raw:
        return RAW + "/" + encoded
    return REPO + ("/tree/main/" if is_dir else "/blob/main/") + encoded


@lru_cache(maxsize=1)
def tracked_paths() -> tuple[set[str], set[str]]:
    result = subprocess.run(
        ["git", "ls-files", "-z"], cwd=ROOT, check=True, capture_output=True,
    )
    files = {part.decode() for part in result.stdout.split(b"\0") if part}
    directories = set()
    for path in files:
        parts = path.split("/")
        directories.update("/".join(parts[:n]) for n in range(1, len(parts)))
    return files, directories


def rewrite_url(slug: str, url: str, slugs: set[str], image: bool = False) -> str:
    parts = urlsplit(url)
    if parts.scheme or parts.netloc or url.startswith("#") or url.startswith("//"):
        return url
    if not parts.path:
        return url
    source = parts.path
    if source.startswith("/"):
        return url
    root_relative = source.startswith(("rnd/", "notes/", "src/", "research/", "docs/", "data/", "bin/", "scripts/", "site/"))
    if root_relative and (ROOT / source).exists():
        target = posixpath.normpath(source)
    else:
        target = posixpath.normpath(f"rnd/{slug}/{source}")
    if target.startswith("../"):
        return url
    target_parts = target.split("/")
    if len(target_parts) >= 2 and target_parts[0] == "rnd" and target_parts[1] in slugs:
        if len(target_parts) == 2 or (len(target_parts) == 3 and target_parts[2] == "README.md"):
            suffix = ("?" + parts.query if parts.query else "") + ("#" + parts.fragment if parts.fragment else "")
            return target_parts[1] + ".html" + suffix
    path = ROOT / target
    is_dir = source.endswith("/") or path.is_dir()
    base = repo_url(target, is_dir=is_dir, raw=image)
    return base + ("?" + parts.query if parts.query else "") + ("#" + parts.fragment if parts.fragment else "")


def inline_code_url(slug: str, value: str, slugs: set[str]) -> str | None:
    """Link repo paths in README code spans, including research/ultra paths."""
    if not value or re.search(r"[\s*{}<>]", value) or value.startswith(("-", "$", "~", "/")):
        return None
    if "/" not in value and Path(value).suffix not in {".md", ".py", ".cr", ".cu", ".json", ".yml", ".yaml", ".sh"}:
        return None
    root_path = posixpath.normpath(value)
    experiment_path = posixpath.normpath(f"rnd/{slug}/{value}")
    ultra_path = posixpath.normpath(f"research/ultra/{value}")
    root_prefix = value.startswith(("rnd/", "notes/", "src/", "research/", "docs/", "data/", "bin/", "scripts/", "site/"))
    candidates = [root_path, experiment_path, ultra_path] if root_prefix else [experiment_path, root_path, ultra_path]
    files, directories = tracked_paths()
    for path in candidates:
        if path in files or path in directories:
            return rewrite_url(slug, path, slugs)
    if "/" not in value:
        ultra_matches = [path for path in files if path.startswith("research/ultra/") and path.endswith("/" + value)]
        if len(ultra_matches) == 1:
            return rewrite_url(slug, ultra_matches[0], slugs)
    return None


def heading_slug(text: str) -> str:
    text = unicodedata.normalize("NFKC", text).lower()
    text = re.sub(r"[^\w\s-]", "", text, flags=re.UNICODE)
    return re.sub(r"\s+", "-", text.strip())


def render_markdown(slug: str, body: str, slugs: set[str]) -> str:
    tokens = MD.parse(body)
    used_ids = {}
    for index, token in enumerate(tokens):
        if token.type == "heading_open":
            # The page title is h1; README headings live beneath it.
            level = min(int(token.tag[1]) + 1, 6)
            token.tag = f"h{level}"
            if index + 1 < len(tokens):
                inline = tokens[index + 1]
                title = "".join(child.content for child in (inline.children or []) if child.type in ("text", "code_inline"))
                base = heading_slug(title) or "section"
                occurrence = used_ids.get(base, 0)
                used_ids[base] = occurrence + 1
                token.attrSet("id", base if occurrence == 0 else f"{base}-{occurrence}")
        elif token.type == "heading_close":
            token.tag = f"h{min(int(token.tag[1]) + 1, 6)}"
        if token.type == "inline":
            children = []
            link_depth = 0
            for child in token.children or []:
                if child.type == "link_open":
                    href = child.attrGet("href")
                    if href:
                        child.attrSet("href", rewrite_url(slug, href, slugs))
                    link_depth += 1
                elif child.type == "link_close":
                    link_depth -= 1
                elif child.type == "image":
                    src = child.attrGet("src")
                    if src:
                        child.attrSet("src", rewrite_url(slug, src, slugs, image=True))
                elif child.type == "code_inline" and link_depth == 0:
                    href = inline_code_url(slug, child.content, slugs)
                    if href:
                        opening = Token("link_open", "a", 1)
                        opening.attrSet("href", href)
                        children.extend((opening, child, Token("link_close", "a", -1)))
                        continue
                children.append(child)
            token.children = children
    return MD.renderer.render(tokens, MD.options, {})


