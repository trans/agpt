def local_links(items: list[str], slugs: set[str]) -> str:
    links = []
    for name in items:
        if name in slugs:
            links.append(f'<a href="{escape(name)}.html">{escape(name)} <span aria-hidden="true">↗</span></a>')
        else:
            links.append(f'<span>{escape(name)}</span>')
    return "".join(links) if links else '<span class="empty-value">None listed</span>'


def code_link(slug: str, code: object) -> str:
    if code == "main":
        return repo_url(f"rnd/{slug}", is_dir=True)
    tag = code.get("tag") or code["branch"]
    return REPO + "/tree/" + quote(str(tag), safe="/-._~")


def detail(record: dict, slugs: set[str]) -> str:
    fm, slug = record["fm"], record["slug"]
    headlines = []
    for item in fm.get("headline") or []:
        run = item.get("run")
        run_info = record["headline_runs"].get(str(run)) if run else None
        date = run_info[1] if run_info else None
        extra = headline_caveats(fm, date)
        run_link = f'<a href="{escape(run_info[0])}">Run record ↗</a>' if run_info else ""
        headlines.append(f"""<div class="headline-item">
          <span class="headline-label">{escape(item["label"])}</span>
          <strong>{escape(item["value"])}</strong>
          <span class="headline-metric">{escape(item["metric"])}</span>
          <span class="headline-extra">{run_link}{"".join(badge(name, "badge-caveat", description) for name, description in extra)}</span>
        </div>""")
    headline_html = '<section class="headline-grid" aria-label="Headline results">' + "".join(headlines) + "</section>" if headlines else ""
    tags = fm.get("tags") or []
    tag_html = "".join(f'<a class="tag-link" href="index.html?tag={quote(str(tag))}">{escape(tag)}</a>' for tag in tags) or '<span class="empty-value">None listed</span>'
    body = render_markdown(slug, record["body"], slugs)
    content = f"""<section class="experiment-hero">
      <div class="shell">
        <a class="back-link" href="index.html">← All experiments</a>
        <span class="section-number">THE RESEARCH RECORD / {escape(slug)}</span>
        <h1>{escape(fm["title"])}</h1>
        <p class="experiment-question">{escape(fm["question"])}</p>
        {badge_row(fm)}
{run_history_summary(record)}
        <div class="experiment-dates"><span>Opened <time datetime="{escape(fm["opened"])}">{escape(fm["opened"])}</time></span><span>Updated <time datetime="{escape(fm["updated"])}">{escape(fm["updated"])}</time></span></div>
      </div>
    </section>
    <div class="shell experiment-main">
      <section class="answer-panel" aria-labelledby="answer-heading"><span id="answer-heading" class="micro-label">THE ANSWER SO FAR</span><p>{escape(fm.get("answer") or "This question is still open.")}</p></section>
{headline_html}
      <section class="experiment-meta" aria-label="Experiment connections">
        <div><span class="micro-label">TOPICS</span><div class="meta-links">{tag_html}</div></div>
        <div><span class="micro-label">RELATED</span><div class="meta-links">{local_links(fm.get("related") or [], slugs)}</div></div>
        <div><span class="micro-label">SUPERSEDED BY</span><div class="meta-links">{local_links(fm.get("superseded_by") or [], slugs)}</div></div>
        <div><span class="micro-label">CODE</span><div class="meta-links"><a href="{escape(code_link(slug, fm["code"]))}">{escape("Main branch" if fm["code"] == "main" else fm["code"].get("tag") or fm["code"]["branch"])} ↗</a></div></div>
      </section>
      <div class="record-heading"><div><span class="section-number">THE FULL RECORD</span><h2>Experiment notes</h2></div><a href="{repo_url(f"rnd/{slug}", is_dir=True)}">Open directory on GitHub ↗</a></div>
      <article class="experiment-body">{body}</article>
      <div class="record-end"><a href="{repo_url(f"rnd/{slug}", is_dir=True)}">View the experiment directory on GitHub ↗</a><a href="index.html">Browse all experiments →</a></div>
    </div>"""
    return page(fm["title"], fm["question"], content, slug=slug)


def select_control(name: str, values: list[str]) -> str:
    options = '<option value="">All</option>' + "".join(f'<option value="{escape(value)}">{escape(value)}</option>' for value in values)
    return f'<label><span>{escape(name)}</span><select data-filter="{escape(name.lower())}">{options}</select></label>'


def index_page(entries: list[dict]) -> str:
    family = sorted({r["fm"]["family"] for r in entries})
    kind = sorted({r["fm"]["kind"] for r in entries})
    status = sorted({r["fm"]["status"] for r in entries})
    outcome = sorted({r["fm"]["outcome"] for r in entries})
    evaluation = sorted({r["fm"]["eval"] for r in entries})
    tags = sorted({tag for r in entries for tag in r["fm"].get("tags") or []})
    controls = "".join([
        select_control("Kind", kind), select_control("Status", status),
        select_control("Outcome", outcome), select_control("Family", family),
        select_control("Eval", evaluation), select_control("Tag", tags),
    ])
    rows = []
    for record in sorted(entries, key=lambda r: (date_value(r["fm"]["updated"]) or dt.date.min, r["slug"]), reverse=True):
        fm, slug = record["fm"], record["slug"]
        search = " ".join([fm["title"], fm["question"], " ".join(fm.get("tags") or []), slug]).lower()
        attrs = {
            "kind": fm["kind"], "status": fm["status"], "outcome": fm["outcome"],
            "family": fm["family"], "eval": fm["eval"],
            "tags": "|".join(fm.get("tags") or []), "search": search,
            "updated": str(fm["updated"]),
        }
        data = " ".join(f'data-{key}="{escape(value)}"' for key, value in attrs.items())
        rows.append(f"""<article class="experiment-row" {data}>
          <div class="row-main"><span class="row-slug">rnd/{escape(slug)}</span><h2><a href="{escape(slug)}.html">{escape(fm["title"])} <span aria-hidden="true">↗</span></a></h2><p>{escape(fm["question"])}</p></div>
          <div class="row-meta"><div class="badge-row">{badge(fm["outcome"], "badge-outcome outcome-" + fm["outcome"].replace("/", "-"))}{badge(fm["family"], "badge-family")}</div><div class="row-dates">Opened {escape(fm["opened"])}<br>Updated {escape(fm["updated"])}</div></div>
        </article>""")
    content = f"""<section class="experiment-hero index-hero"><div class="shell">
      <span class="section-number">THE RESEARCH RECORD</span><h1>Every experiment.<br><em>One place.</em></h1>
      <p class="experiment-question">Explore the tests, diagnostics, baselines, designs, and infrastructure behind AGPT. Each page preserves its protocol and links to the full record.</p>
      <p class="index-count">{len(entries)} published records · attention, recurrent, count-prior, and hybrid work</p>
    </div></section>
    <section class="shell experiment-main index-main" aria-label="Experiment index">
      <div class="filter-panel">
        <div class="filter-top"><div><span class="micro-label">FIND AN EXPERIMENT</span><p>Filter the research record.</p></div><button id="clear-filters" type="button">Clear filters</button></div>
        <label class="search-control"><span>Search title, question, or tag</span><input id="experiment-search" type="search" placeholder="Search experiments…" autocomplete="off"></label>
        <div class="filter-grid">{controls}
          <label><span>Updated</span><select id="date-sort"><option value="newest">Newest first</option><option value="oldest">Oldest first</option></select></label>
        </div>
      </div>
      <div class="results-heading"><span id="result-count" aria-live="polite">{len(entries)} experiments</span><span>Click a title for the full record</span></div>
      <div id="experiment-list" class="experiment-list">{"".join(rows)}</div>
      <p id="no-results" class="no-results" hidden>No experiments match these filters. <button type="button" data-clear>Clear filters</button></p>
    </section>"""
    return page("All experiments", "Search the AGPT experiment record.", content, script="experiments.js")


def main() -> None:
    entries = records()
    slugs = {record["slug"] for record in entries}
    OUTPUT.mkdir(parents=True, exist_ok=True)
    expected = {"index.html"} | {slug + ".html" for slug in slugs}
    for old in OUTPUT.glob("*.html"):
        if old.name not in expected and old.read_text(encoding="utf-8").find(GENERATED_MARKER) >= 0:
            old.unlink()
    (OUTPUT / "index.html").write_text(index_page(entries), encoding="utf-8")
    for record in entries:
        (OUTPUT / (record["slug"] + ".html")).write_text(detail(record, slugs), encoding="utf-8")
    print(f"Built {len(entries)} experiment pages and index in {OUTPUT.relative_to(ROOT)}/")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, subprocess.CalledProcessError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
